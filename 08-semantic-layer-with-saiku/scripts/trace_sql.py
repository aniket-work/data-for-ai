"""Show the SQL that Mondrian generated for the most recent MDX query (our own helper).

Reads saiku-home/logs/mondrian-sql.log, written by saiku/log4j2-sql.xml.
Usage: python3 scripts/trace_sql.py <saiku-home> [--mdx-only]
"""
import re, sys
from rich.console import Console
from rich.syntax import Syntax
from rich.rule import Rule

home = sys.argv[1]
log = open(f"{home}/logs/mondrian-sql.log", encoding="utf-8", errors="replace").read()
# MDX statements are logged as "<id>: <mdx>" blocks; SQL as "<id>: <reader>: executing sql [ ... ]"
mdx_blocks = [m for m in re.finditer(r"^(\d+): ((?:with|select)\b.*?)(?=\n\n)", log, re.S | re.M | re.I)
              if "[Box Office]" in m.group(2)]
if not mdx_blocks:
    sys.exit("No Box Office MDX in the log yet: run a query in Saiku first.")
last = mdx_blocks[-1]
qid, mdx = last.group(1), last.group(2).strip()
end = re.search(rf"^{qid}: exec: (\d+) ms", log[last.end():], re.M)
chunk = log[last.end(): last.end() + (end.start() if end else len(log))]
sqls = [s.strip() for s in re.findall(r"executing sql \[\n?(.*?)\]\n", chunk, re.S)]
sqls = [s for s in sqls if "fact_screening" in s]

c = Console(width=140, force_terminal=True)
c.print(Rule("[bold #34D399]MDX from Saiku"))
c.print(Syntax(mdx, "sql", theme="monokai", background_color="default", word_wrap=True))
if "--mdx-only" not in sys.argv:
    for i, s in enumerate(sqls, 1):
        c.print(Rule(f"[bold #34D399]SQL generated by Mondrian ({i} of {len(sqls)})"))
        c.print(Syntax(s, "sql", theme="monokai", background_color="default", word_wrap=True))
if end:
    c.print(f"[dim]MDX executed in {end.group(1)} ms[/dim]")
